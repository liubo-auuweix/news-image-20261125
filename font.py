GLYPH_W = 5
GLYPH_H = 7
ADVANCE = 6  # glyph width plus one pixel of letter spacing


def text_width(text, scale):
    """Pixel width of `text` drawn at `scale`, no trailing spacing."""
    if not text:
        return 0
    return (len(text) * ADVANCE - 1) * scale


def text_height(scale):
    """Pixel height of one line of text drawn at `scale`."""
    return GLYPH_H * scale


def draw_text(canvas, x, y, text, color, scale):
    """Draw `text` on `canvas` with its top-left corner at (x, y).

    Characters outside the font fall back to a blank glyph. The text is
    rendered in capitals: the poster only ever passes upper-case text.
    """
    cx = x
    for ch in text:
        glyph = GLYPHS.get(ch)
        if glyph is None:
            glyph = GLYPHS[" "]
        for row in range(GLYPH_H):
            bits = glyph[row]
            for col in range(GLYPH_W):
                if bits[col] == "#":
                    canvas.fill_rect(
                        cx + col * scale,
                        y + row * scale,
                        scale,
                        scale,
                        color,
                    )
        cx += ADVANCE * scale
    return cx


def draw_text_centered(canvas, cx, y, text, color, scale):
    """Draw `text` centred on horizontal position `cx`."""
    w = text_width(text, scale)
    draw_text(canvas, cx - w // 2, y, text, color, scale)
    return w


def wrap_text(text, scale, max_width):
    """Split `text` into lines that fit `max_width` pixels at `scale`.

    Words are kept whole where they fit; a single over-long word is
    hard-split. Returns a list of lines (possibly one).
    """
    words = text.split(" ")
    lines = []
    current = ""
    for word in words:
        trial = word if not current else current + " " + word
        if text_width(trial, scale) <= max_width:
            current = trial
            continue
        if current:
            lines.append(current)
        while text_width(word, scale) > max_width and len(word) > 1:
            take = 1
            while (
                take < len(word)
                and text_width(word[: take + 1], scale) <= max_width
            ):
                take += 1
            lines.append(word[:take])
            word = word[take:]
        current = word
    if current:
        lines.append(current)
    return lines
